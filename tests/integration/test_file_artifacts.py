class IngestFileMetrics(IngestFiles):
    """Measure generated bytes through the standard file ingestion contract."""

    name = "ingest_file_metrics_test"

    class OutputRole(StrEnum):
        metrics = auto()

    outputs: ClassVar[dict[str, OutputSpec]] = {
        OutputRole.metrics: OutputSpec(
            artifact_type="metric",
            derives_from={"inputs": ["file"]},
        )
    }

    def convert_file(
        self,
        file_ref: FileRefArtifact,
        step_number: int,
        *,
        fs: AbstractFileSystem | None = None,
    ) -> MetricArtifact:
        content = file_ref.read_content(fs=fs)
        return MetricArtifact.draft(
            content={
                "source_id": file_ref.artifact_id,
                "content_hash": compute_content_digest(content),
                "size_bytes": len(content),
            },
            original_name=f"{file_ref.original_name}.json",
            step_number=step_number,
        )


